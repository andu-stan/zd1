#!/usr/bin/env python3
"""Generate mcu/src/dsp_data.c from the ADAU1445 data extracted from stock 2.04.05 (re/mcu/extracted/dsp/: download_sequence.bin,
which re/scripts/extract_dsp.py writes, and runtime_tables.txt).

    python3 -I mcu/tools/gen_dsp_data.py      rewrites mcu/src/dsp_data.c"""

import os
import re
import struct
import zlib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
EX = ROOT + "/re/mcu/extracted/dsp/"
OUT = ROOT + "/mcu/src/dsp_data.c"

seq = open(EX + "download_sequence.bin", "rb").read()
recs, i = [], 0
while i < len(seq):
    addr, ln = struct.unpack(">HH", seq[i : i + 4])
    recs.append((addr, seq[i + 4 : i + 4 + ln]))
    i += 4 + ln
rt = open(EX + "runtime_tables.txt").read()
vol = [int(m, 16) for m in re.findall(r"^idx\s+\d+: 0x([0-9a-f]{8})", rt, re.M)]
bass = [[int(x, 16) for x in re.findall(r"0x([0-9a-f]{8})\(", l)] for l in rt.splitlines() if l.startswith("entry ")]
assert len(vol) == 72 and len(bass) == 5 and all(len(b) == 5 for b in bass), (len(vol), len(bass))


def carr(name, data):
    lines = [", ".join("0x%02x" % b for b in data[j : j + 16]) for j in range(0, len(data), 16)]
    return "static const uint8_t %s[%d] = {\n    %s\n};\n" % (name, max(len(data), 1), ",\n    ".join(lines) or "0")


o = [
    "/* GENERATED by mcu/tools/gen_dsp_data.py from re/mcu/extracted/dsp/ (stock ZD1 2.04.05) -- do not edit. */",
    '#include "dsp_data.h"',
    "",
]
for n, (a, d) in enumerate(recs):
    o.append("/* step %d: subaddr 0x%04x, %d bytes, crc32 %08x */" % (n, a, len(d), zlib.crc32(d) & 0xFFFFFFFF))
    o.append(carr("step%02d" % n, d))
o.append("const dsp_rec_t dsp_download[DSP_DOWNLOAD_STEPS] = {")
o += ["    { 0x%04x, %5d, step%02d }," % (a, len(d), n) for n, (a, d) in enumerate(recs)]
o.append("};\n")
o.append("/* master volume, DSP index 0..71 (+10 dB .. -60 dB in 1 dB steps, 71 = mute), 5.23 -> param 0x4B */")
o.append(
    "const uint32_t dsp_volume_coef[72] = {\n    "
    + ",\n    ".join(", ".join("0x%08x" % v for v in vol[j : j + 6]) for j in range(0, 72, 6))
    + "\n};\n"
)
o.append('/* bass presets 0..4 (stock labels "Bass 0/+1/-1/-2/-3"), biquad b0 b1 b2 a1 a2 -> params 0x3F..0x43 */')
o.append(
    "const uint32_t dsp_bass_coef[5][5] = {\n"
    + ",\n".join("    { " + ", ".join("0x%08x" % v for v in b) + " }" for b in bass)
    + "\n};"
)
open(OUT, "w").write("\n".join(o) + "\n")
print("wrote %s: %d download steps, %d bytes" % (OUT, len(recs), sum(len(d) for _, d in recs)))
