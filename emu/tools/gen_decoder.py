#!/usr/bin/env python3
"""Generate the AVR32 instruction decoder (C#) from avr32/insn.decode (QEMU decodetree syntax, our patched copy).

    python3 emu/tools/gen_decoder.py                   # writes emu/renode/avr32/Avr32Decoder.g.cs

Only the subset of decodetree the file uses: argument sets (&), formats (@), patterns, fixed bits 0/1, don't-care '.',
unsigned fields name:len. A 16-bit pattern occupies the upper half of the 32-bit instruction word, like QEMU's
--varinsnwidth 32 (the first halfword is fetched into bits 31..16).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "renode", "avr32", "insn.decode")
OUT = os.path.join(HERE, "..", "renode", "avr32", "Avr32Decoder.g.cs")


def bits(tokens):
    """tokens -> (width, mask, value, {field: (pos, len)}) with pos counted from the LSB of the pattern."""
    seq = []  # MSB first: '0', '1', '.', or ('field', name, len)
    for t in tokens:
        m = re.fullmatch(r"([a-z_][a-z0-9_]*):(\d+)", t)
        if m:
            seq.append(("f", m.group(1), int(m.group(2))))
        elif re.fullmatch(r"[01.\-]+", t):
            seq.extend(t)
        else:
            raise ValueError("bad token %r" % t)
    width = sum(x[2] if isinstance(x, tuple) else 1 for x in seq)
    mask = value = 0
    fields = {}
    pos = width
    for x in seq:
        if isinstance(x, tuple):
            pos -= x[2]
            fields[x[1]] = (pos, x[2])
        else:
            pos -= 1
            if x in "01":
                mask |= 1 << pos
                value |= int(x) << pos
    return width, mask, value, fields


def parse(path):
    formats, patterns = {}, []
    for ln, line in enumerate(open(path), 1):
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("&"):
            continue
        toks = line.split()
        name, rest = toks[0], toks[1:]
        bt = [t for t in rest if not t.startswith(("@", "&"))]
        fmt = next((t[1:] for t in rest if t.startswith("@")), None)
        w, mask, value, fields = bits(bt)
        if name.startswith("@"):
            formats[name[1:]] = (w, mask, value, fields)
            continue
        if fmt:
            fw, fmask, fvalue, ffields = formats[fmt]
            if fw != w:
                raise ValueError("line %d: %s width %d, format %s width %d" % (ln, name, w, fmt, fw))
            if fmask & mask and (fvalue & fmask & mask) != (value & fmask & mask):
                raise ValueError("line %d: %s conflicts with its format" % (ln, name))
            mask |= fmask
            value |= fvalue
            fields = dict(ffields, **fields)
        if w == 16:  # first halfword = bits 31..16 of the instruction word
            mask, value = mask << 16, value << 16
            fields = {k: (p + 16, n) for k, (p, n) in fields.items()}
        elif w != 32:
            raise ValueError("line %d: width %d" % (ln, w))
        patterns.append(dict(name=name, len=w // 8, mask=mask, value=value, fields=fields, line=ln))
    return patterns


def check_overlaps(pats):
    for i, a in enumerate(pats):
        for b in pats[i + 1 :]:
            m = a["mask"] & b["mask"]
            if (a["value"] & m) == (b["value"] & m) and a["len"] == b["len"]:
                raise ValueError(
                    "overlap: %s (line %d) and %s (line %d)" % (a["name"], a["line"], b["name"], b["line"])
                )


def main():
    pats = parse(SRC)
    check_overlaps(pats)
    names = sorted({p["name"] for p in pats})
    fields = sorted({f for p in pats for f in p["fields"]})
    o = []
    o.append("// GENERATED by emu/tools/gen_decoder.py from avr32/insn.decode. Do not edit.")
    o.append("using System.Collections.Generic;")
    o.append("")
    o.append("namespace Antmicro.Renode.Peripherals.CPU")
    o.append("{")
    o.append("    public enum Avr32Op : ushort")
    o.append("    {")
    o.append("        Invalid,")
    for n in names:
        o.append("        %s," % n)
    o.append("    }")
    o.append("")
    o.append("    public sealed class Avr32Insn")
    o.append("    {")
    o.append("        public Avr32Op Op;")
    o.append("        public uint Raw;")
    o.append("        public int Len;")
    o.append("        public int %s;" % ", ".join(fields))
    o.append("    }")
    o.append("")
    o.append("    public static class Avr32Decoder")
    o.append("    {")
    o.append("        // mask, value, length in bytes, op")
    o.append("        static readonly (uint mask, uint value, int len, Avr32Op op)[] Patterns =")
    o.append("        {")
    for p in pats:
        o.append(
            "            (0x%08Xu, 0x%08Xu, %d, Avr32Op.%s),   // insn.decode:%d"
            % (p["mask"], p["value"], p["len"], p["name"], p["line"])
        )
    o.append("        };")
    o.append("")
    o.append("        static readonly int[][] ByHalfword = Build();")
    o.append("")
    o.append("        static int[][] Build()")
    o.append("        {")
    o.append("            var t = new int[65536][];")
    o.append("            var l = new List<int>();")
    o.append("            for(var hw = 0u; hw < 65536; hw++)")
    o.append("            {")
    o.append("                l.Clear();")
    o.append("                var len = (hw >> 13) == 7 ? 4 : 2;")
    o.append("                for(var i = 0; i < Patterns.Length; i++)")
    o.append("                {")
    o.append("                    var p = Patterns[i];")
    o.append("                    if(p.len == len && ((hw << 16) & p.mask & 0xFFFF0000u) == (p.value & 0xFFFF0000u))")
    o.append("                    {")
    o.append("                        l.Add(i);")
    o.append("                    }")
    o.append("                }")
    o.append("                t[hw] = l.ToArray();")
    o.append("            }")
    o.append("            return t;")
    o.append("        }")
    o.append("")
    o.append(
        "        /// <summary>Instruction length from the first halfword: 32 bits when its top three bits are 111.</summary>"
    )
    o.append("        public static int Length(uint firstHalfword) => (firstHalfword >> 13) == 7 ? 4 : 2;")
    o.append("")
    o.append("        /// <summary>insn: first halfword in bits 31..16, second (if any) in 15..0.</summary>")
    o.append("        public static void Decode(uint insn, Avr32Insn d)")
    o.append("        {")
    o.append("            d.Raw = insn;")
    o.append("            d.Len = Length(insn >> 16);")
    o.append("            d.Op = Avr32Op.Invalid;")
    o.append("            foreach(var i in ByHalfword[insn >> 16])")
    o.append("            {")
    o.append("                var p = Patterns[i];")
    o.append("                if((insn & p.mask) == p.value)")
    o.append("                {")
    o.append("                    d.Op = p.op;")
    o.append("                    break;")
    o.append("                }")
    o.append("            }")
    o.append("            switch(d.Op)")
    o.append("            {")
    for n in names:
        p = next(x for x in pats if x["name"] == n)
        if not p["fields"]:
            continue
        o.append("            case Avr32Op.%s:" % n)
        for f, (pos, ln) in sorted(p["fields"].items()):
            o.append("                d.%s = (int)((insn >> %d) & 0x%X);" % (f, pos, (1 << ln) - 1))
        o.append("                break;")
    o.append("            }")
    o.append("        }")
    o.append("    }")
    o.append("}")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("%d patterns, %d ops, %d fields -> %s" % (len(pats), len(names), len(fields), os.path.relpath(OUT)))


if __name__ == "__main__":
    sys.exit(main())
