//! zd1-protogen: what the MCU's C and the references take from the two protocol specs, written into the repo (the
//! computer's side, host/core, uses the specs' crates directly). From the SPI protocol (zd1-spi):
//!   mcu/src/zd1link_gen.h                         registers, kinds, DRC codes + acks, the spec's groups of values:
//!                                                 C, header-only
//!   mcu/test/zd1link_gen_test.c                   the MCU's C (zd1link.h on zd1link_gen.h) against vectors computed
//!                                                 by the Rust implementation
//!   docs/protocol/registers.md                     the register and DRC reference
//! from the host link (zd1-hostlink, host.rs here):
//!   mcu/src/zd1host_gen.h                          message structs and the codec, C (header-only)
//!   mcu/test/zd1host_gen_test.c                    the C codec against the reference encoder's vectors
//!   docs/protocol/host.md                          the reference
//!
//!   protocol/host/spec.lock                        every message and field the host link has had (it may only grow)
//!
//!   cargo run --manifest-path protocol/gen/Cargo.toml [-- --check]   (--check: fail if a file is stale)
//!   ... -- --break                                 accept a host-link break (only with a new VERSION)

use std::fmt::Write as _;
use zd1_spi::codec::{net, play, volume};

mod host;
use zd1_spi::framing::{self, READ_F, READ_V, WRITE_V};
use zd1_spi::spec::{self, Drc, Kind, Payload, REGISTERS};

/// What each generated file says it comes from.
pub(crate) const SPI_HEADER: &str =
    "Generated by protocol/gen from protocol/spi (the MCU <-> module SPI protocol): do not edit, regenerate.";
pub(crate) const HOST_HEADER: &str =
    "Generated by protocol/gen from protocol/host (the computer <-> MCU USB protocol): do not edit, regenerate.";

fn access(a: u8) -> String {
    let mut s = String::new();
    if a & spec::R != 0 {
        s.push('R');
    }
    if a & spec::W != 0 {
        s.push('W');
    }
    if a & spec::N != 0 {
        s.push('N');
    }
    s
}

fn payload(p: Payload) -> String {
    match p {
        Payload::U16 => "u16".into(),
        Payload::Ascii2 => "2 ASCII".into(),
        Payload::CStr { max } => format!("string + NUL, <= {max}"),
        Payload::Text { max } => format!("text, <= {max}"),
        Payload::Bytes { max } => format!("bytes, <= {max}"),
        Payload::Volume => "volume 03 03 01 vv".into(),
        Payload::PlayXml => "DRC XML".into(),
        Payload::Config => "config [op][n][name][value]".into(),
        Payload::Drc => "DRC code".into(),
    }
}

pub(crate) fn c_comment(s: &str) -> String {
    s.replace("*/", "* /")
}

fn header_h() -> String {
    let mut s = format!(
        "/* {SPI_HEADER}\n * The MCU <-> module SPI register protocol (docs/protocol/registers.md): its values. The code on top of\n * them (framing, payloads) is mcu/src/zd1link.h. */\n#ifndef ZD1LINK_GEN_H\n#define ZD1LINK_GEN_H\n#include <stdbool.h>\n#include <stdint.h>\n\n"
    );
    s += "/* ---- registers ---- */\n";
    for r in REGISTERS {
        writeln!(
            s,
            "#define ZD1_REG_{:<18} 0x{:02X}  /* {} {}: {} */",
            r.name,
            r.num,
            if r.kind == Kind::F { 'F' } else { 'V' },
            access(r.access),
            c_comment(r.doc)
        )
        .unwrap();
    }
    s += "\n/* 'F' (2 data bytes) or 'V' (16-bit LE length + data) for every register: ours, else the stock firmware's table */\nstatic inline char zd1_reg_kind(uint8_t reg){\n    static const uint8_t v[32] = {";
    for i in 0..32u8 {
        let mut bits = 0u8;
        for j in 0..8u8 {
            if spec::kind(i * 8 + j) == Kind::V {
                bits |= 1 << j;
            }
        }
        write!(s, "{}0x{bits:02X}", if i > 0 { "," } else { "" }).unwrap();
    }
    s += "};\n    return (v[reg >> 3] >> (reg & 7)) & 1 ? 'V' : 'F';\n}\n";
    s += "\n/* ---- DRC codes (MCU -> module on 0x48, b0) ---- */\n";
    for d in Drc::ALL {
        writeln!(
            s,
            "#define ZD1_DRC_{:<14} 0x{:02X}  /* ack {}: {} */",
            screaming(d.name()),
            d.code(),
            d.ack().map(|a| a.to_string()).unwrap_or("-".into()),
            c_comment(d.doc())
        )
        .unwrap();
    }
    s += "/* the value the module acknowledges a DRC code with on 0xE3 (b0), or -1 (no ack) */\nstatic inline int zd1_drc_ack(uint8_t code){\n    switch(code){\n";
    for d in Drc::ALL {
        if let Some(a) = d.ack() {
            writeln!(s, "    case ZD1_DRC_{}: return {a};", screaming(d.name())).unwrap();
        }
    }
    s += "    default: return -1;\n    }\n}\n";
    for g in spec::CONSTS {
        writeln!(s, "\n/* ---- {}: {} ---- */", g.name, c_comment(g.doc)).unwrap();
        for c in g.items {
            let v = match (c.value)() {
                spec::Value::Int(n) if n > 9 => format!("0x{n:02X}"),
                spec::Value::Int(n) => n.to_string(),
                spec::Value::Str(t) => format!("{t:?}"),
            };
            let name = format!("ZD1_{}_{}", g.name.to_uppercase(), c.name);
            if c.doc.is_empty() {
                writeln!(s, "#define {name:<26} {v}").unwrap();
            } else {
                writeln!(s, "#define {name:<26} {v}  /* {} */", c_comment(c.doc)).unwrap();
            }
        }
    }
    s += "\n#endif\n";
    s
}

pub(crate) fn screaming(camel: &str) -> String {
    let mut s = String::new();
    for (i, c) in camel.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            s.push('_');
        }
        s.push(c.to_ascii_uppercase());
    }
    s
}

fn bytes(f: impl FnOnce(&mut dyn FnMut(u8))) -> Vec<u8> {
    let mut v = Vec::new();
    f(&mut |b| v.push(b));
    v
}
fn c_array(v: &[u8]) -> String {
    v.iter().map(|b| format!("0x{b:02X}")).collect::<Vec<_>>().join(",")
}

/// The C helpers against the Rust implementation: vectors computed here, baked into a host test program.
fn test_c() -> String {
    let mut s = format!(
        "/* {SPI_HEADER}\n * Host test of mcu/src/zd1link.h and zd1link_gen.h against the Rust implementation (zd1-spi):\n *   cc -I mcu/src -o /tmp/t mcu/test/zd1link_gen_test.c && /tmp/t */\n#include <stdio.h>\n#include <string.h>\n#include \"zd1link.h\"\nstatic int fails;\n#define CHECK(c, ...) do {{ if(!(c)){{ fails++; printf(\"FAIL \" __VA_ARGS__); printf(\"\\n\"); }} }} while(0)\n\n"
    );
    // stuffing every byte value, and whole messages built the Rust way, unstuffed the C way
    s += "static void stuffing(void){\n    uint8_t o[2];\n";
    for b in 0..=255u8 {
        let v = bytes(|o| framing::stuff(b, &mut |x| o(x)));
        writeln!(s, "    {{ uint8_t e[] = {{{}}}; uint8_t n = zd1_stuff(0x{b:02X}, o); CHECK(n == {} && !memcmp(o, e, n), \"stuff %02x\", 0x{b:02X}); }}", c_array(&v), v.len()).unwrap();
    }
    s += "}\n\nstatic void unstuff_msg(const uint8_t *w, int n, const uint8_t *want, int wn, const char *what){\n    zd1_unstuff_t u = {0}; uint8_t got[300]; int k = 0, i; uint8_t b;\n    for(i = 0; i < n; i++) if(zd1_unstuff(&u, w[i], &b) == ZD1_RX_BYTE && k < 300) got[k++] = b;\n    CHECK(k == wn && !memcmp(got, want, wn), \"unstuff %s\", what);\n}\nstatic void messages(void){\n";
    let cases: Vec<(&str, Vec<u8>, Vec<u8>)> = vec![
        ("read V 0x27", bytes(|o| framing::request(READ_V, 0x27, 0, 0, &mut |x| o(x))), vec![READ_V, 0x27, 0, 0]),
        (
            "reply V 0x27",
            bytes(|o| framing::reply_v(0x27, b"C 2014092908219112\0", &mut |x| o(x))),
            [vec![READ_V, 0x27, 19, 0], b"C 2014092908219112\0".to_vec()].concat(),
        ),
        (
            "reply F 0x32",
            bytes(|o| framing::reply_f(READ_F, 0x32, 0x3231, &mut |x| o(x))),
            vec![READ_F, 0x32, 0x32, 0x31],
        ),
        (
            "write V 0x40 mute",
            bytes(|o| framing::write_v(0x40, &volume::encode(volume::MUTE), &mut |x| o(x))),
            vec![WRITE_V, 0x40, 4, 0, 3, 3, 1, 0xFF],
        ),
    ];
    for (what, wire, plain) in &cases {
        writeln!(
            s,
            "    {{ uint8_t w[] = {{{}}}, p[] = {{{}}}; unstuff_msg(w, sizeof w, p, sizeof p, \"{what}\"); }}",
            c_array(wire),
            c_array(plain)
        )
        .unwrap();
    }
    s += "}\n\nstatic void volumes(void){\n";
    for att in 0..=255u8 {
        writeln!(
            s,
            "    CHECK(zd1_volume_step_from_att({att}) == {}, \"step_from_att {att}\");",
            volume::step_from_att(att)
        )
        .unwrap();
    }
    for step in 0..=volume::STEPS {
        writeln!(
            s,
            "    CHECK(zd1_volume_att_from_step({step}) == {}, \"att_from_step {step}\");",
            volume::att_from_step(step)
        )
        .unwrap();
    }
    s += "}\n\nstatic void kinds_and_codes(void){\n";
    for n in 0..=255u8 {
        writeln!(
            s,
            "    CHECK(zd1_reg_kind(0x{n:02X}) == '{}', \"kind %02x\", 0x{n:02X});",
            if spec::kind(n) == Kind::F { 'F' } else { 'V' }
        )
        .unwrap();
    }
    for d in Drc::ALL {
        writeln!(
            s,
            "    CHECK(zd1_drc_ack(0x{:02X}) == {}, \"ack %02x\", 0x{:02X});",
            d.code(),
            d.ack().map(|a| a as i32).unwrap_or(-1),
            d.code()
        )
        .unwrap();
    }
    writeln!(
        s,
        "    CHECK(zd1_net_connected('2', '1') == {} && zd1_net_connected('0', '0') == {}, \"net\");",
        net::is_connected(net::CONNECTED),
        net::is_connected(net::DOWN)
    )
    .unwrap();
    s += "}\n\nstatic void play_icons(void){\n";
    for p in [play::Play::Playing, play::Play::Paused, play::Play::Empty] {
        let mut x = Vec::new();
        play::xml(p, &mut |b| x.extend_from_slice(b));
        let want = match p {
            play::Play::Playing => "ZD1_PLAY_PLAYING",
            play::Play::Paused => "ZD1_PLAY_PAUSED",
            play::Play::Empty => "ZD1_PLAY_EMPTY",
        };
        writeln!(s, "    {{ zd1_play_matcher_t m = {{0}}; const char x[] = {:?}; int r = ZD1_PLAY_NONE, i; for(i = 0; x[i]; i++){{ int v = zd1_play_push(&m, x[i]); if(v) r = v; }} CHECK(r == {want}, \"play %s\", x); }}",
                 String::from_utf8(x).unwrap()).unwrap();
    }
    s += "}\n\nint main(void){\n    stuffing(); messages(); volumes(); kinds_and_codes(); play_icons();\n    printf(fails ? \"zd1link_gen: %d FAILED\\n\" : \"zd1link_gen: all ok\\n\", fails);\n    return fails != 0;\n}\n";
    s
}

fn docs() -> String {
    let mut s = format!(
        "# MCU <-> module registers (generated)\n\n<!-- {SPI_HEADER} -->\n\nThe registers our code uses, from the protocol spec (`protocol/spi/src/spec.rs`). Kind: F = 2 data bytes, V = 16-bit\nlength + data. Access: R = the MCU reads, W = the MCU writes, N = the module notifies (0x0C names it, the MCU reads\nit, F or V). Every byte on the wire is stuffed (`protocol/spi/src/framing.rs`). Evidence and the stock firmware's\nhandling: `docs/protocol/spi-registers.md`.\n\n| Reg | Name | Kind | Access | Payload | |\n|---|---|---|---|---|---|\n"
    );
    for r in REGISTERS {
        writeln!(
            s,
            "| 0x{:02X} | {} | {} | {} | {} | {} |",
            r.num,
            r.name,
            if r.kind == Kind::F { 'F' } else { 'V' },
            access(r.access),
            payload(r.payload),
            r.doc.replace('|', "\\|")
        )
        .unwrap();
    }
    s += "\n## DRC codes (0x48, b0)\n\n| Code | Name | Ack (0xE3 b0) | |\n|---|---|---|---|\n";
    for d in Drc::ALL {
        writeln!(
            s,
            "| 0x{:02X} | {} | {} | {} |",
            d.code(),
            d.name(),
            d.ack().map(|a| a.to_string()).unwrap_or("-".into()),
            d.doc()
        )
        .unwrap();
    }
    s
}

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    let brk = std::env::args().any(|a| a == "--break");
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    // the host link's compatibility (protocol/host/src/lib.rs): the spec may only grow over what spec.lock records
    let lock = std::fs::read_to_string(root.join("protocol/host/spec.lock")).unwrap_or_default();
    let breaks = host::lock_breaks(&lock);
    if !breaks.is_empty() {
        for b in &breaks {
            println!("host link break: {b}");
        }
        let bumped = !breaks.iter().any(|b| b.starts_with("version"));
        if !brk || bumped {
            println!(
                "the host link may only grow (docs/protocol/host.md, Compatibility); a real break: bump VERSION in \
                      protocol/host/src/lib.rs and run with --break"
            );
            std::process::exit(1);
        }
    }
    let outs = [
        ("mcu/src/zd1link_gen.h", header_h()),
        ("mcu/test/zd1link_gen_test.c", test_c()),
        ("docs/protocol/registers.md", docs()),
        ("mcu/src/zd1host_gen.h", host::header_h()),
        ("mcu/test/zd1host_gen_test.c", host::test_c()),
        ("docs/protocol/host.md", host::docs()),
        ("protocol/host/spec.lock", host::lock_text()),
    ];
    let mut stale = 0;
    for (p, text) in outs {
        let path = root.join(p);
        let old = std::fs::read_to_string(&path).unwrap_or_default();
        if old == text {
            continue;
        }
        if check {
            println!("stale: {p}");
            stale += 1;
            continue;
        }
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, text).unwrap();
        println!("wrote {p}");
    }
    std::process::exit(if stale > 0 { 1 } else { 0 });
}
