// The interface's constants (../w0abi.h) and the images' symbols (NAME.sym, for hang reports) as Rust; the images
// themselves (module/warp0/build.py: emu/img/warp0/, or W0_FW_DIR) are src/warp.rs's include_bytes! from
// W0_FW_DIR, which this resolves (cargo tracks those files itself).
use std::{env, fs, path::PathBuf};

const IMAGES: [&str; 4] = ["w0fw", "w0aac", "w0vorbis", "w0flac"];

/// `#define NAME <number or expression>` -> `pub const NAME: u32 = ...;` (C's `u` suffixes dropped)
fn abi(header: &str) -> String {
    let mut out = String::from("// generated from w0abi.h by build.rs\n");
    // a define continued with `\` is one line
    for line in header.replace("\\\n", " ").lines() {
        let Some(rest) = line.trim().strip_prefix("#define ") else { continue };
        let mut it = rest.splitn(2, char::is_whitespace);
        let (Some(name), Some(value)) = (it.next(), it.next()) else { continue };
        let value = value.split("/*").next().unwrap().trim();
        if value.is_empty() || name.contains('(') {
            continue;
        }
        let mut v = String::new();
        let mut prev_digit = false;
        for c in value.chars() {
            if c == 'u' && prev_digit {
                continue; // 0x...u, 32u
            }
            prev_digit = c.is_ascii_hexdigit() || c == 'x';
            v.push(c);
        }
        out += &format!("#[allow(dead_code, unused_parens)]\npub const {name}: u32 = {v};\n");
    }
    out
}

fn main() {
    let here = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let fw_dir = env::var("W0_FW_DIR").map(PathBuf::from).unwrap_or_else(|_| here.join("../../../emu/img/warp0"));
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    println!("cargo:rustc-env=W0_FW_DIR={}", fw_dir.canonicalize().unwrap().display());
    let mut syms = String::from("// generated by build.rs from the images' .sym files\n");
    for name in IMAGES {
        let path = fw_dir.join(format!("{name}.sym"));
        let text =
            fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e} (run module/warp0/build.py)", path.display()));
        let entries: Vec<String> =
            text.lines().filter_map(|l| l.split_once(' ')).map(|(a, n)| format!("(0x{a}, \"{n}\")")).collect();
        syms += &format!("pub static {}: &[(u32, &str)] = &[{}];\n", name.to_uppercase(), entries.join(", "));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    fs::write(out.join("symbols.rs"), syms).unwrap();
    let header = fs::read_to_string(here.join("../w0abi.h")).unwrap();
    fs::write(out.join("abi.rs"), abi(&header)).unwrap();
    println!("cargo:rerun-if-changed={}", here.join("../w0abi.h").display());
    println!("cargo:rerun-if-env-changed=W0_FW_DIR");
}
