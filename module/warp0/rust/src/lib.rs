/// A stream's job queue on Warp0 (realtime packets, buffered ALAC or AAC frames): a unit in if there is room
/// (`false`: full, too big, or the queue is off after a hang or a job error), results out in order.
#[cfg(feature = "airplay")]
pub(crate) trait Jobs: Send {
    fn submit(&mut self, unit: &[u8]) -> bool;
    /// The finished units, oldest first, until one isn't.
    fn collect(&mut self, done: &mut dyn FnMut(shairplay::decoder::Decoded));
    /// Not off (a hang, a job error): units may still go to Warp0.
    fn live(&self) -> bool;
    /// Every slot taken: a unit has to wait for one.
    fn full(&self) -> bool;
}

/// Where a unit is.
#[cfg(feature = "airplay")]
#[derive(PartialEq)]
enum Side {
    Warp,
    /// Waiting for a slot on Warp0
    Waiting,
    Arm,
}

/// A stream's shairplay-rust `Decoder`: each unit to Warp0, waiting for a slot while its queue is full, or to the
/// ARM's decoder (the one the stream would have without Warp0) when Warp0 is off or won't take it; the samples come
/// back in the order the units went in, whichever decoded them. A full queue isn't a reason for the ARM: it decodes
/// as the unit is sent, in the receiver's loop, so a burst after a network stall (a couple of hundred realtime
/// packets at once, ~3 ms each there) would hold the loop off its socket for most of a second, where Warp0 gets
/// through ~500 packets a second beside it.
#[cfg(feature = "airplay")]
pub struct OnWarp {
    jobs: Box<dyn Jobs>,
    arm: Box<dyn shairplay::decoder::Decoder>,
    order: std::collections::VecDeque<Side>,
    /// Units waiting for a slot, in order
    waiting: std::collections::VecDeque<Vec<u8>>,
    /// Warp0's results not handed out yet, in order
    done: std::collections::VecDeque<shairplay::decoder::Decoded>,
}

/// Units waiting for Warp0 at most (~2 s of realtime packets); past that (Warp0 slow, not stopped) the ARM's.
#[cfg(feature = "airplay")]
const WAITING_MAX: usize = 256;

#[cfg(feature = "airplay")]
impl OnWarp {
    fn new(jobs: Box<dyn Jobs>, arm: Box<dyn shairplay::decoder::Decoder>) -> Self {
        OnWarp { jobs, arm, order: Default::default(), waiting: Default::default(), done: Default::default() }
    }

    /// Waiting units onto Warp0 while there are slots; to the ARM once it is off (or if it won't take one).
    fn pump(&mut self) {
        while let Some(unit) = self.waiting.front() {
            let side = if self.jobs.live() && self.jobs.submit(unit) {
                Side::Warp
            } else if self.jobs.live() && self.jobs.full() {
                return;
            } else {
                self.arm.send(unit);
                Side::Arm
            };
            self.waiting.pop_front();
            if let Some(s) = self.order.iter_mut().find(|s| **s == Side::Waiting) {
                *s = side;
            }
        }
    }
}

#[cfg(feature = "airplay")]
impl shairplay::decoder::Decoder for OnWarp {
    fn send(&mut self, unit: &[u8]) {
        self.pump();
        if !self.waiting.is_empty() && self.waiting.len() < WAITING_MAX {
            self.waiting.push_back(unit.to_vec());
            self.order.push_back(Side::Waiting);
        } else if self.waiting.is_empty() && self.jobs.submit(unit) {
            self.order.push_back(Side::Warp);
        } else if self.waiting.is_empty() && self.jobs.live() && self.jobs.full() {
            self.waiting.push_back(unit.to_vec());
            self.order.push_back(Side::Waiting);
        } else {
            self.arm.send(unit);
            self.order.push_back(Side::Arm);
        }
    }

    fn receive(&mut self) -> Option<shairplay::decoder::Decoded> {
        if !self.waiting.is_empty() {
            let done = &mut self.done;
            self.jobs.collect(&mut |out| done.push_back(out));
            self.pump();
        }
        match self.order.front()? {
            Side::Waiting => None,
            Side::Arm => {
                let d = self.arm.receive()?;
                self.order.pop_front();
                Some(d)
            }
            Side::Warp => {
                if self.done.is_empty() {
                    let done = &mut self.done;
                    self.jobs.collect(&mut |out| done.push_back(out));
                }
                let out = self.done.pop_front()?;
                self.order.pop_front();
                Some(out)
            }
        }
    }

    /// While Warp0 takes units: they come back later, so the stream sends them ahead (after a hang, the ARM decodes
    /// each when it is due).
    fn background(&self) -> bool {
        self.jobs.live()
    }
}

/// shairplay-rust's decoders for every AirPlay stream: Warp0 when it is free (`enabled`) and decodes the stream
/// (realtime packets decrypted there too), with the ARM's decoder for what it doesn't take; without Warp0 the ARM's
/// alone. The ARM's: shairplay's own, but for AAC ours (module/codecs/aac).
#[cfg(feature = "airplay")]
pub fn decoders(enabled: bool) -> shairplay::decoder::DecoderFactory {
    use shairplay::decoder::{Codec, Framing, builtin};
    std::sync::Arc::new(move |info| {
        let arm = match info.codec {
            Codec::Aac => zd1_aac::decoder(info.sample_rate, info.channels),
            _ => builtin(info),
        }?;
        if !enabled {
            return Some(arm);
        }
        let warp: Result<Box<dyn Jobs>, String> = match (&info.codec, &info.framing) {
            (Codec::Alac(p), Framing::Rtp(cipher)) => rtp::Packets::new(cipher, p).map(|j| Box::new(j) as _),
            (Codec::Alac(p), Framing::Frames) => AlacWarp::new(p).map(|j| Box::new(j) as _),
            (Codec::Aac, Framing::Frames) => AacWarp::new(info.sample_rate, info.channels).map(|j| Box::new(j) as _),
            _ => Err("not a stream Warp0 decodes".into()),
        };
        match warp {
            Ok(jobs) => {
                let what = if matches!(info.framing, Framing::Rtp(_)) { "decrypts and decodes" } else { "decodes" };
                tracing::info!(codec = ?info.codec, rate = info.sample_rate, bits = info.bit_depth, "Warp0 {what} this stream");
                Some(Box::new(OnWarp::new(jobs, arm)))
            }
            Err(e) => {
                tracing::info!(%e, codec = ?info.codec, "Warp0 not used for this stream: the ARM decodes it");
                Some(arm)
            }
        }
    })
}

#[cfg(all(test, feature = "airplay"))]
mod tests {
    use super::*;
    use shairplay::decoder::{Decoded, Decoder};
    use std::sync::{Arc, Mutex};

    /// Warp0's queue as a test drives it: takes up to `slots` units while live, finishes them when told; a unit [k]
    /// decodes to [k, k].
    #[derive(Clone)]
    struct FakeJobs(Arc<Mutex<(bool, std::collections::VecDeque<(i16, bool)>)>>, usize);
    impl FakeJobs {
        fn new(slots: usize) -> Self {
            FakeJobs(Arc::new(Mutex::new((true, Default::default()))), slots)
        }
        fn finish_all(&self) {
            self.0.lock().unwrap().1.iter_mut().for_each(|e| e.1 = true);
        }
    }
    impl Jobs for FakeJobs {
        fn submit(&mut self, unit: &[u8]) -> bool {
            let mut s = self.0.lock().unwrap();
            let take = s.0 && s.1.len() < self.1;
            if take {
                s.1.push_back((unit[0] as i16, false));
            }
            take
        }
        fn collect(&mut self, done: &mut dyn FnMut(Decoded)) {
            let mut s = self.0.lock().unwrap();
            while let Some(&(k, true)) = s.1.front() {
                s.1.pop_front();
                done(Decoded::S16(vec![k, k]));
            }
        }
        fn live(&self) -> bool {
            self.0.lock().unwrap().0
        }
        fn full(&self) -> bool {
            self.0.lock().unwrap().1.len() >= self.1
        }
    }

    /// The ARM: a unit [k] decodes to [-k, -k] when it is sent.
    struct Arm(std::collections::VecDeque<i16>);
    impl Decoder for Arm {
        fn send(&mut self, unit: &[u8]) {
            self.0.push_back(-(unit[0] as i16));
        }
        fn receive(&mut self) -> Option<Decoded> {
            let k = self.0.pop_front()?;
            Some(Decoded::S16(vec![k, k]))
        }
    }

    fn out(d: &mut OnWarp) -> Vec<i16> {
        std::iter::from_fn(|| match d.receive()? {
            Decoded::S16(s) => Some(s[0]),
            _ => None,
        })
        .collect()
    }

    /// Units go to the ARM when Warp0 is off, and everything comes back in the order it went in: an ARM unit behind
    /// one still on Warp0 waits for it.
    #[test]
    fn warp0_and_the_arm_come_back_in_order() {
        let jobs = FakeJobs::new(8);
        let mut d = OnWarp::new(Box::new(jobs.clone()), Box::new(Arm(Default::default())));
        d.send(&[1]);
        jobs.0.lock().unwrap().0 = false; // off: the ARM's
        d.send(&[2]);
        assert!(!d.background());
        jobs.0.lock().unwrap().0 = true;
        d.send(&[3]);
        assert!(out(&mut d).is_empty(), "the first is still on Warp0");
        assert!(d.background());
        jobs.finish_all();
        assert_eq!(out(&mut d), [1, -2, 3]);
    }

    /// A full queue makes units wait for a slot (none goes to the ARM), in order; once Warp0 is off, what waits goes
    /// to the ARM, still in order.
    #[test]
    fn a_full_queue_makes_units_wait_for_warp0_not_go_to_the_arm() {
        let jobs = FakeJobs::new(2);
        let mut d = OnWarp::new(Box::new(jobs.clone()), Box::new(Arm(Default::default())));
        for k in 1..=5 {
            d.send(&[k]);
        }
        assert!(out(&mut d).is_empty());
        jobs.finish_all();
        assert_eq!(out(&mut d), [1, 2], "3 and 4 took the free slots meanwhile");
        jobs.finish_all();
        assert_eq!(out(&mut d), [3, 4]);
        d.send(&[6]); // 5 is on Warp0 now, and a slot is free for 6
        jobs.finish_all();
        jobs.0.lock().unwrap().0 = false; // 5 and 6 done, then Warp0 off: 7 to the ARM
        d.send(&[7]);
        assert_eq!(out(&mut d), [5, 6, -7]);
        // waiting when Warp0 goes off: to the ARM, in order
        let jobs = FakeJobs::new(1);
        let mut d = OnWarp::new(Box::new(jobs.clone()), Box::new(Arm(Default::default())));
        for k in 1..=3 {
            d.send(&[k]);
        }
        jobs.0.lock().unwrap().0 = false;
        jobs.finish_all();
        assert_eq!(out(&mut d), [1, -2, -3]);
    }
}
