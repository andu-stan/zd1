//! Warp0 from Rust: the client (the firmware images built in), and the stream decoders built on it.
//!
//! - [`warp`]: one booted image owned by one user (a lock file keeps a second one out), its buffers and ring; a job that doesn't finish is diagnosed (the control block, the PC and the function
//!   it is in, or that the core no longer enters debug mode), counted for this boot and logged to
//!   [`warp::HANG_LOG`], and the core parked. After [`ZD1_WARP0_MAX_HANGS`](warp) hangs in one boot Warp0 is left
//!   alone until the next.
//! - [`queue`]: a stream's jobs in order, each with its own buffers; the users below are that plus their fields.
//! - [`rtp`]: realtime AirPlay packets, decrypted and ALAC-decoded;
//! - [`aac`]: buffered AirPlay's AAC frames;
//! - [`alac`]: buffered AirPlay's ALAC frames, 16- and 24-bit;
//!   each a shairplay-rust `Decoder` through [`OnWarp`], all from [`decoders`] (`RaopServerBuilder::decoders`).
//! - [`vorbis`]: Spotify's Ogg Vorbis packets (zd1-spotify).
//! - [`flac`]: a Snapcast server's FLAC chunks (zd1-snapcast).
//!
//! Every user falls back to the ARM's copy of its decoder when Warp0 is taken, refuses the stream, or hangs.

