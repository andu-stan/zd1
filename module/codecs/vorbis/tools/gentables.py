#!/usr/bin/env python3
"""Generate module/codecs/vorbis/vorbis_tables.c: the Vorbis decoder's (../vorbisdec.c) constant tables, fixed point.

floor 1's inverse dB table is the specification's (libvorbis's FLOOR1_fromdB_LOOKUP, lib/floor1.c, BSD-3-Clause,
libvorbis 1.3.7 here) in Q31; the windows are computed (the specification's "Vorbis window"). The output is
committed; run this only to change it.

  python3 -I module/codecs/vorbis/tools/gentables.py PATH/TO/libvorbis/lib/floor1.c > module/codecs/vorbis/vorbis_tables.c
"""

import math
import re
import sys

src = open(sys.argv[1]).read()
m = re.search(r"FLOOR1_fromdB_LOOKUP\[256\]\s*=\s*\{(.*?)\};", src, re.S)
db = [float(v.rstrip("Ff")) for v in re.findall(r"[0-9.]+(?:e[-+]?\d+)?F", m.group(1))]
assert len(db) == 256 and db[-1] == 1.0, len(db)

out = ["/* Generated by module/codecs/vorbis/tools/gentables.py. Do not edit. */", '#include "vorbis_tables.h"', ""]


def q31(x):
    return max(-0x80000000, min(0x7FFFFFFF, int(round(x * 2147483648.0))))


def table(ctype, name, vals, per=8):
    out.append("VORBIS_FAST const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), per):
        out.append("    " + " ".join("%d," % v for v in vals[i : i + per]))
    out.append("};")


table("int32_t", "vorbis_floor1_db", [q31(v) for v in db])
# rising window slopes of n samples: sin(pi/2 sin^2((i + 1/2) / n * pi/2)), Q31 (block sizes 256 and 2048)
for n in (128, 1024):
    table(
        "int32_t",
        "vorbis_win_%d" % n,
        [q31(math.sin(math.pi / 2 * math.sin((i + 0.5) / n * math.pi / 2) ** 2)) for i in range(n)],
    )
print("\n".join(out))
