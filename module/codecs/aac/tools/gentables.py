#!/usr/bin/env python3
"""Generate module/codecs/aac/aac_tables.c: the AAC-LC tables our decoder (../aacdec.c) needs, in fixed point.

The codebooks and band tables are the standard's (ISO/IEC 14496-3 / 13818-7), read from FFmpeg's transcription
(libavcodec/aactab.c, LGPL-2.1+; FFmpeg 8.1.3 here). Everything else is computed: windows (sine, KBD as FFmpeg's
kbdwin.c), x^(4/3). The IMDCT's tables are module/codecs/dsp's. The output is committed; run this only to change it.

  python3 -I module/codecs/aac/tools/gentables.py PATH/TO/ffmpeg/libavcodec/aactab.c > module/codecs/aac/aac_tables.c
"""

import math
import re
import sys

ROOT = 8  # first-level lookup bits of every Huffman table

src = open(sys.argv[1]).read()


def array(name):
    m = re.search(r"\b%s\s*\[[^\]]*\]\s*=\s*\{(.*?)\};" % re.escape(name), src, re.S)
    if not m:
        raise SystemExit("no table " + name)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


def ffloats(name):
    m = re.search(r"\b%s\s*\[[^\]]*\]\s*=\s*\{(.*?)\};" % re.escape(name), src, re.S)
    return [float(v) for v in re.findall(r"-?\d+\.\d+", m.group(1))]


out = []
w = out.append
w(
    "/* Generated by module/codecs/aac/tools/gentables.py from FFmpeg's transcription of the AAC standard's tables\n"
    " * (libavcodec/aactab.c) and computed windows / twiddles. Do not edit. */"
)
w('#include "aac_tables.h"\n')


def huffman(name, codes, bits, values):
    """Two-level lookup: root[peek(ROOT)] is a leaf (value << 16 | length) or a subtable link
    (0x8000 | offset << 16 | subbits); subtable leaves hold the length beyond ROOT."""
    table = [None] * (1 << ROOT)
    subs = {}
    for c, l, v in zip(codes, bits, values):
        if l <= ROOT:
            base = c << (ROOT - l)
            for i in range(1 << (ROOT - l)):
                table[base + i] = (v << 16) | l
        else:
            subs.setdefault(c >> (l - ROOT), []).append((c, l, v))
    entries = list(table)
    for prefix, lst in sorted(subs.items()):
        sb = max(l for _, l, _ in lst) - ROOT
        off = len(entries)
        entries += [None] * (1 << sb)
        for c, l, v in lst:
            rest = l - ROOT
            low = c & ((1 << rest) - 1)
            base = low << (sb - rest)
            for i in range(1 << (sb - rest)):
                entries[off + base + i] = (v << 16) | rest
        assert table[prefix] is None and off < 0x8000
        entries[prefix] = 0x8000 | (off << 16) | sb
    entries = [0 if e is None else e for e in entries]
    w("const uint32_t %s[%d] = {" % (name, len(entries)))
    for i in range(0, len(entries), 8):
        w("    " + " ".join("0x%08x," % e for e in entries[i : i + 8]))
    w("};")
    return len(entries)


# scalefactor book: value = index (the decoder subtracts 60)
huffman("aac_huff_sf", array("ff_aac_scalefactor_code"), array("ff_aac_scalefactor_bits"), list(range(121)))

# spectral books: leaf value packs the decoded numbers
#   books 1-4 (quads): 4 x 4-bit two's complement, w in the top nibble; books 5-11 (pairs): 2 x 8-bit, y high
for b in range(1, 12):
    codes, bits = array("codes%d" % b), array("bits%d" % b)
    vals = []
    for i in range(len(codes)):
        if b <= 4:
            if b <= 2:
                q = [i // 27 - 1, i // 9 % 3 - 1, i // 3 % 3 - 1, i % 3 - 1]
            else:
                q = [i // 27, i // 9 % 3, i // 3 % 3, i % 3]
            vals.append(sum((q[j] & 0xF) << (12 - 4 * j) for j in range(4)))
        else:
            mod = {5: 9, 6: 9, 7: 8, 8: 8, 9: 13, 10: 13, 11: 17}[b]
            y, z = i // mod, i % mod
            if b <= 6:
                y, z = y - 4, z - 4
            vals.append(((y & 0xFF) << 8) | (z & 0xFF))
    huffman("aac_huff_%d" % b, codes, bits, vals)
w("const uint32_t *const aac_huff_spec[12] = { 0, " + ", ".join("aac_huff_%d" % b for b in range(1, 12)) + " };\n")

# scalefactor bands, per sampling-frequency index (0 = 96 kHz .. 12 = 7.35 kHz)
LONG = ["96", "96", "64", "48", "48", "32", "24", "24", "16", "16", "16", "8", "8"]
SHORT = ["96", "96", "96", "48", "48", "48", "24", "24", "16", "16", "16", "8", "8"]
for n in sorted(set(LONG)):
    w("static const uint16_t swb_long_%s[] = {%s};" % (n, ", ".join(map(str, array("swb_offset_1024_" + n)))))
for n in sorted(set(SHORT)):
    w("static const uint16_t swb_short_%s[] = {%s};" % (n, ", ".join(map(str, array("swb_offset_128_" + n)))))
w("const uint16_t *const aac_swb_long[13] = {%s};" % ", ".join("swb_long_" + n for n in LONG))
w("const uint16_t *const aac_swb_short[13] = {%s};" % ", ".join("swb_short_" + n for n in SHORT))
w("const uint8_t aac_num_swb_long[13] = {%s};" % ", ".join(map(str, array("ff_aac_num_swb_1024"))))
w("const uint8_t aac_num_swb_short[13] = {%s};" % ", ".join(map(str, array("ff_aac_num_swb_128"))))
w("const uint8_t aac_tns_max_bands_long[13] = {%s};" % ", ".join(map(str, array("ff_tns_max_bands_1024"))))
w("const uint8_t aac_tns_max_bands_short[13] = {%s};\n" % ", ".join(map(str, array("ff_tns_max_bands_128"))))


def q31(x):
    return max(-0x80000000, min(0x7FFFFFFF, int(round(x * 2147483648.0))))


FAST = ("aac_win_",)


def table(ctype, name, vals, per=8, fmt="%d"):
    fast = "AAC_FAST " if name.startswith(FAST) else ""
    w("%sconst %s %s[%d] = {" % (fast, ctype, name, len(vals)))
    for i in range(0, len(vals), per):
        w("    " + " ".join((fmt % v) + "," for v in vals[i : i + per]))
    w("};")


# x^(4/3), Q17, for 0..1024 (larger values interpolate between entries x >> 3: |x| <= 8191)
table("uint32_t", "aac_pow43", [int(round(i ** (4 / 3) * (1 << 17))) for i in range(1025)])
# 2^(f/4), Q30
table("uint32_t", "aac_pow2_frac", [int(round(2 ** (f / 4) * (1 << 30))) for f in range(4)])

# TNS reflection coefficients: index [coef_compress * 2 + coef_res], as FFmpeg's ff_tns_tmp2_map (Q31)
for name in ("tns_tmp2_map_0_3", "tns_tmp2_map_0_4", "tns_tmp2_map_1_3", "tns_tmp2_map_1_4"):
    table("int32_t", "aac_" + name, [q31(v) for v in ffloats(name)], fmt="%d")
w(
    "const int32_t *const aac_tns_coef[4] = {aac_tns_tmp2_map_0_3, aac_tns_tmp2_map_0_4, aac_tns_tmp2_map_1_3, "
    "aac_tns_tmp2_map_1_4};\n"
)


def bessel_i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-20 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def kbd(alpha, n):
    a2 = 4 * (alpha * math.pi / n) ** 2
    temp = [bessel_i0(math.sqrt(i * (n - i) * a2)) for i in range(n // 2 + 1)]
    scale = 1.0 / (sum(temp[i] * (1 + (0 < i < n // 2)) for i in range(n // 2 + 1)) + 1)
    win, s = [], 0.0
    for i in range(n // 2 + 1):
        s += temp[i]
        win.append(math.sqrt(s * scale))
    for i in range(n // 2 + 1, n):
        s += temp[n - i]
        win.append(math.sqrt(s * scale))
    return win


def sine(n):
    return [math.sin((i + 0.5) * math.pi / (2 * n)) for i in range(n)]


# rising window halves, Q31: [shape][...], shape 0 = sine, 1 = KBD
table("int32_t", "aac_win_long_sine", [q31(v) for v in sine(1024)])
table("int32_t", "aac_win_long_kbd", [q31(v) for v in kbd(4.0, 1024)])
table("int32_t", "aac_win_short_sine", [q31(v) for v in sine(128)])
table("int32_t", "aac_win_short_kbd", [q31(v) for v in kbd(6.0, 128)])

print("\n".join(out))
