#!/usr/bin/env python3
"""Generate module/codecs/dsp/imdct_tables.c: the IMDCT's twiddles and bit reversal (../imdct.c), fixed point. The output
is committed; run this only to change it.

  python3 -I module/codecs/dsp/tools/gentables.py > module/codecs/dsp/imdct_tables.c
"""

import math

out = ["/* Generated by module/codecs/dsp/tools/gentables.py. Do not edit. */", '#include "imdct.h"', ""]


def q31(x):
    return max(-0x80000000, min(0x7FFFFFFF, int(round(x * 2147483648.0))))


def table(ctype, name, vals, per=8):
    out.append("DSP_FAST const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), per):
        out.append("    " + " ".join("%d," % v for v in vals[i : i + per]))
    out.append("};")


# IMDCT pre/post twiddles exp(-i 2 pi (k + 1/8) / N), interleaved cos, sin (Q31): N = 2048 and 256
for n in (2048, 256):
    tw = []
    for k in range(n // 4):
        a = -2 * math.pi * (k + 0.125) / n
        tw += [q31(math.cos(a)), q31(math.sin(a))]
    table("int32_t", "dsp_imdct_tw_%d" % n, tw)
# FFT twiddles exp(-i 2 pi j / 512), j < 384 (radix-4: W^j, W^2j, W^3j), interleaved cos, sin, Q30 (a high-word
# multiply by them is a product / 4: the radix-4 stage's scaling)
fft = []
for j in range(384):
    a = -2 * math.pi * j / 512
    fft += [int(round(math.cos(a) * (1 << 30))), int(round(math.sin(a) * (1 << 30)))]
table("int32_t", "dsp_fft_tw", fft)
# bit reversal, 9 bits (the 64-point FFT uses the top 6: rev9(i << 3))
table("uint16_t", "dsp_bitrev9", [int(f"{i:09b}"[::-1], 2) for i in range(512)], per=16)

print("\n".join(out))
